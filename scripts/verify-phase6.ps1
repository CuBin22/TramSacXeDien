# Run from any directory. Each native command must succeed before continuing.
[CmdletBinding()]
param([switch]$SkipE2E)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot

function Invoke-Step {
    param([string]$Title, [string]$Command, [string[]]$Arguments)
    Write-Host "`n=== $Title ===" -ForegroundColor Cyan
    & $Command @Arguments
    if ($LASTEXITCODE -ne 0) {
        throw "$Title failed (exit code $LASTEXITCODE)."
    }
}

Push-Location $repoRoot
try {
    $required = @('mvn', 'npm', 'docker')
    if (-not $SkipE2E) { $required += 'python' }
    foreach ($command in $required) {
        if (-not (Get-Command $command -ErrorAction SilentlyContinue)) {
            throw "Missing command: $command. See docs/GIAI_DOAN_6.md."
        }
    }
    Invoke-Step 'Docker engine' 'docker' @('info', '--format', '{{.ServerVersion}}')
    # Clean removes stale .class files generated by the IDE after dependency changes.
    Invoke-Step 'Java: clean verify (all modules)' 'mvn' @('-B', '-ntp', 'clean', 'verify')
    Push-Location (Join-Path $repoRoot 'web')
    try {
        Invoke-Step 'React: install locked dependencies' 'npm' @('ci')
        Invoke-Step 'React: tests' 'npm' @('test')
        Invoke-Step 'React: production build' 'npm' @('run', 'build')
    } finally {
        Pop-Location
    }
    if (-not $SkipE2E) {
        Invoke-Step 'Real simulators and Jaeger E2E' 'python' @('scripts/verify-e2e.py')
        Write-Host 'PASS: Java, React, build and simulator E2E.' -ForegroundColor Green
    } else {
        Write-Host 'PASS: Java, React and build. E2E was skipped.' -ForegroundColor Yellow
    }
} finally {
    Pop-Location
}
